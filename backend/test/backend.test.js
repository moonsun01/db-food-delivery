const { test } = require('node:test');
const assert = require('node:assert/strict');
const { fixture, OPERATIONS_KEY } = require('./helpers');
const { previousWeek, weekBounds } = require('../services/settlements');

test('all 36 frontend APIs: customer -> owner -> rider -> weekly settlement -> logout', async () => {
  const c = await fixture();
  const { call, app, customer, owner, rider } = c;
  const sid = c.restaurant.id;
  assert.equal(customer.user.id, owner.user.id, 'role-scoped numeric identities intentionally overlap');
  assert.equal(owner.user.id, rider.user.id);
  assert.equal('phone' in owner.user, false);
  assert.equal(rider.user.status, '운행종료');
  assert.equal(c.restaurant.status, '영업종료');
  assert.equal(c.restaurant.deliveryFee, 0);
  assert.deepEqual(await call('GET', '/api/health'), { status: 'ok' });
  assert.equal((await call('GET', '/api/me', undefined, customer.token)).id, customer.user.id);
  await call('PATCH', '/api/me', { name: '수정 고객', phone: '010-0000-0001' }, customer.token);
  await call('PATCH', '/api/me', { name: '수정 점주' }, owner.token);
  assert.equal((await call('GET', '/api/addresses', undefined, customer.token)).length, 1);
  await call('GET', `/api/addresses/${c.address.id}`, undefined, customer.token);
  await call('PATCH', `/api/addresses/${c.address.id}`, { detailAddress: null }, customer.token);
  const spare = await call('POST', '/api/addresses', { address: '삭제용 주소' }, customer.token, 201);
  assert.equal(spare.detailAddress, null);
  await call('DELETE', `/api/addresses/${spare.id}`, undefined, customer.token, 204);
  assert.equal((await call('GET', '/api/stores?q=중국')).length, 1);
  await call('GET', `/api/stores/${sid}`);
  assert.equal((await call('GET', '/api/me/stores', undefined, owner.token)).length, 1);
  await call('POST', '/api/stores', { name: '두 번째 가게', address: '주소' }, owner.token, 409);
  assert.equal((await call('GET', `/api/stores/${sid}/menus`)).length, 1);
  await call('PATCH', `/api/stores/${sid}/menus/${c.menu.id}`, { name: '수정 세트' }, owner.token);
  const order = await call('POST', '/api/orders', c.orderInput, customer.token, 201, { 'Idempotency-Key': 'order-one' });
  assert.equal(order.status, '접수대기');
  assert.equal(order.totalAmount, 27000);
  assert.equal(order.payment.amount, 30000);
  assert.equal(order.payment.status, '완료');
  assert.equal(order.payment.canceledAt, null);
  assert.equal(order.delivery, null);
  assert.equal(order.items[0].unitPrice, 27000);
  assert.deepEqual(Object.keys(order).sort(), Object.keys(require('../docs/api-contract.json')[18].response).sort());
  assert.deepEqual(await call('POST', '/api/orders', c.orderInput, customer.token, 200, { 'Idempotency-Key': 'order-one' }), order);
  await call('POST', '/api/orders', { ...c.orderInput, items: [{ menuId: c.menu.id, quantity: 2 }] }, customer.token, 409, { 'Idempotency-Key': 'order-one' });
  assert.equal((await call('GET', '/api/orders?status=접수대기', undefined, customer.token)).length, 1);
  await call('GET', `/api/orders/${order.id}`, undefined, owner.token);
  await call('DELETE', `/api/addresses/${c.address.id}`, undefined, customer.token, 409);
  const payment = await call('GET', `/api/orders/${order.id}/payments`, undefined, customer.token);
  assert.equal(payment.length, 1);
  await call('GET', '/api/payments', undefined, owner.token);
  await call('GET', `/api/payments/${order.payment.id}`, undefined, customer.token);
  await call('GET', `/api/orders/${order.id}/delivery`, undefined, customer.token, 404);
  await call('PATCH', '/api/riders/me/status', { status: '운행가능' }, rider.token);
  assert.deepEqual(await call('GET', '/api/deliveries/available', undefined, rider.token), []);
  await call('POST', `/api/orders/${order.id}/delivery/accept`, {}, rider.token, 409);
  await call('PATCH', `/api/orders/${order.id}/status`, { status: '조리중' }, owner.token);
  await call('PATCH', `/api/orders/${order.id}/status`, { status: '조리완료' }, owner.token);
  assert.equal(app.locals.store.state.deliveries.length, 0, 'delivery starts only on rider acceptance');
  const available = await call('GET', '/api/deliveries/available', undefined, rider.token);
  assert.equal(available[0].orderId, order.id);
  assert.equal('addressSnapshot' in available[0], false);
  const delivery = await call('POST', `/api/orders/${order.id}/delivery/accept`, {}, rider.token, 201);
  assert.equal(delivery.status, '배정완료');
  await call('POST', `/api/orders/${order.id}/delivery/accept`, {}, rider.token);
  await call('PATCH', '/api/riders/me/status', { status: '운행종료' }, rider.token, 409);
  assert.equal((await call('GET', '/api/me', undefined, rider.token)).status, '배달중');
  await call('GET', `/api/orders/${order.id}/delivery`, undefined, customer.token);
  await call('GET', '/api/deliveries', undefined, owner.token);
  await call('GET', `/api/deliveries/${delivery.id}`, undefined, rider.token);
  await call('PATCH', `/api/deliveries/${delivery.id}/status`, { status: '배달완료' }, rider.token, 409);
  for (const status of ['픽업완료', '배달중', '배달완료']) {
    await call('PATCH', `/api/deliveries/${delivery.id}/status`, { status }, rider.token);
    await call('PATCH', `/api/deliveries/${delivery.id}/status`, { status }, rider.token);
  }
  const history = await call('GET', `/api/deliveries/${delivery.id}/history`, undefined, customer.token);
  assert.deepEqual(history.map((row) => row.status), ['배정완료', '픽업완료', '배달중', '배달완료']);
  assert.equal((await call('GET', '/api/me', undefined, rider.token)).status, '운행가능');
  const completed = await call('GET', `/api/orders/${order.id}`, undefined, rider.token);
  assert.equal(completed.status, '조리완료');
  assert.equal(completed.delivery.status, '배달완료');
  assert.ok(completed.delivery.completedAt);
  // Closed-week fixture timestamps exercise settlement without adding a client date-override API.
  const startDate = previousWeek();
  const week = weekBounds(startDate);
  app.locals.store.transaction((state) => {
    state.deliveryHistory.filter((row) => row.deliveryId === delivery.id).forEach((row, index) => {
      row.changedAt = new Date(week.from + 3600000 + index * 60000).toISOString();
    });
  });
  const ops = { 'X-Operations-Key': OPERATIONS_KEY };
  const generated = await call('POST', '/internal/settlements/generate', { startDate }, undefined, 201, ops);
  assert.equal(generated.length, 2);
  assert.deepEqual(generated.map((row) => row.amount).sort((a,b) => a-b), [3000, 27000]);
  assert.deepEqual(await call('POST', '/internal/settlements/generate', { startDate }, undefined, 200, ops), []);
  const ownerSettlements = await call('GET', `/api/settlements?startDate=${startDate}`, undefined, owner.token);
  const riderSettlements = await call('GET', '/api/settlements', undefined, rider.token);
  assert.equal(ownerSettlements[0].storeId, sid);
  assert.equal(ownerSettlements[0].riderId, null);
  const settlement = await call('GET', `/api/settlements/${riderSettlements[0].id}`, undefined, rider.token);
  assert.equal(settlement.storeId, null);
  assert.equal(settlement.riderId, rider.user.id);
  assert.deepEqual(settlement.items.map((row) => [row.payTarget, row.payAmount]), [['라이더', 3000]]);
  await call('GET', `/api/settlements/${settlement.id}`, undefined, owner.token, 403);
  await call('POST', `/internal/settlements/${settlement.id}/pay`, {}, undefined, 200, ops);
  assert.equal((await call('GET', `/api/settlements/${settlement.id}`, undefined, rider.token)).status, '지급완료');
  assert.equal(await call('POST', '/api/auth/logout', undefined, customer.token, 204), null);
  await call('GET', '/api/me', undefined, customer.token, 401);
  const expected = require('../docs/api-contract.json').map((api) => `${api.method} ${api.url}`);
  assert.deepEqual(expected.filter((key) => !c.seen.has(key)), [], 'every specified API needs a successful request');
  app.locals.store.close();
});
